// Generates src/tui/intl_tables.rs from node's own ICU data: the time zones
// `Intl.supportedValuesOf('timeZone')` lists, and what the locale editor needs
// from `Intl.getCanonicalLocales` and `Intl.DateTimeFormat.supportedLocalesOf`
// (the languages with date formats, and the language and region aliases).
//
// usage: node tools/gen-intl-tables.mjs > src/tui/intl_tables.rs && cargo fmt
const letters = 'abcdefghijklmnopqrstuvwxyz';

function* codes(alphabet, length) {
    if (length === 0) {
        yield '';
        return;
    }
    for (const head of alphabet) {
        for (const tail of codes(alphabet, length - 1)) {
            yield head + tail;
        }
    }
}

function canonical(tag) {
    try {
        return Intl.getCanonicalLocales(tag)[0] ?? null;
    } catch {
        return null;
    }
}

const languages = [];
const languageAliases = [];
for (const code of [...codes(letters, 2), ...codes(letters, 3)]) {
    const c = canonical(code);
    if (c === null) {
        continue;
    }
    if (c !== code) {
        languageAliases.push([code, c]);
    } else if (Intl.DateTimeFormat.supportedLocalesOf([code]).length > 0) {
        languages.push(code);
    }
}

const regionAliases = [];
for (const region of [...codes(letters.toUpperCase(), 2), ...codes('0123456789', 3)]) {
    const c = canonical(`en-${region}`);
    if (c !== null && c !== `en-${region}`) {
        regionAliases.push([region, c.slice(3)]);
    }
}

// Sorted by code point, for Rust's binary_search on &str
const byCode = (a, b) => (a < b ? -1 : a > b ? 1 : 0);
languages.sort(byCode);
languageAliases.sort((a, b) => byCode(a[0], b[0]));
regionAliases.sort((a, b) => byCode(a[0], b[0]));

const quote = s => JSON.stringify(s);
const out = [];
out.push('// @generated by tools/gen-intl-tables.mjs; do not edit.');
out.push(`// node ${process.version}, icu ${process.versions.icu}, tz ${process.versions.tz}`);
out.push('');
out.push('/// `Intl.supportedValuesOf(\'timeZone\')`.');
out.push('pub static TIME_ZONES: &[&str] = &[');
for (const tz of Intl.supportedValuesOf('timeZone')) {
    out.push(`    ${quote(tz)},`);
}
out.push('];');
out.push('');
out.push('/// Canonical language subtags `Intl.DateTimeFormat.supportedLocalesOf` accepts, sorted.');
out.push('pub static DATE_LANGUAGES: &[&str] = &[');
for (const code of languages) {
    out.push(`    ${quote(code)},`);
}
out.push('];');
out.push('');
out.push('/// Language subtags `Intl.getCanonicalLocales` replaces, sorted, with their replacement tags.');
out.push('pub static LANGUAGE_ALIASES: &[(&str, &str)] = &[');
for (const [from, to] of languageAliases) {
    out.push(`    (${quote(from)}, ${quote(to)}),`);
}
out.push('];');
out.push('');
out.push('/// Region subtags `Intl.getCanonicalLocales` replaces (for `en`), sorted, with their replacements.');
out.push('pub static REGION_ALIASES: &[(&str, &str)] = &[');
for (const [from, to] of regionAliases) {
    out.push(`    (${quote(from)}, ${quote(to)}),`);
}
out.push('];');
console.log(out.join('\n'));
