// Generates src/unicode_tables.rs from the code bundled in an upstream
// ccstatusline dist file (string-width 7.2 / get-east-asian-width / emoji-regex)
// and from node's own Unicode property data, so widths match upstream exactly.
//
// usage: node tools/gen-unicode-tables.mjs <path to dist/ccstatusline-*.js with string-width> > src/unicode_tables.rs
import { readFileSync } from 'node:fs';

const bundlePath = process.argv[2];
if (!bundlePath) {
    console.error('usage: gen-unicode-tables.mjs <bundle.js>');
    process.exit(1);
}
const lines = readFileSync(bundlePath, 'utf8').split('\n');

function sliceBetween(startMarker, endMarker) {
    const start = lines.findIndex(l => l.startsWith(startMarker));
    const end = lines.findIndex((l, i) => i > start && l.startsWith(endMarker));
    if (start < 0 || end < 0) throw new Error(`markers not found: ${startMarker}`);
    return lines.slice(start, end).join('\n');
}

const emojiSrc = sliceBetween('var require_emoji_regex', '// node_modules/');
const eawSrc = sliceBetween('// node_modules/get-east-asian-width/lookup-data.js', '// node_modules/string-width/index.js');

const factory = new Function(`
    const __commonJS = (fn) => () => { const module = { exports: {} }; fn(module.exports, module); return module.exports; };
    ${emojiSrc}
    ${eawSrc}
    return { emojiRegex: require_emoji_regex(), eastAsianWidth };
`);
const { emojiRegex, eastAsianWidth } = factory();

function ranges(pred) {
    const out = [];
    let start = -1;
    for (let cp = 0; cp <= 0x110000; cp++) {
        const ok = cp < 0x110000 && !(cp >= 0xd800 && cp <= 0xdfff) && pred(cp);
        if (ok && start < 0) start = cp;
        if (!ok && start >= 0) {
            out.push([start, cp - 1]);
            start = -1;
        }
    }
    return out;
}

const prop = p => {
    const re = new RegExp(`^\\p{${p}}$`, 'u');
    return cp => re.test(String.fromCodePoint(cp));
};

const tables = {
    WIDE: ranges(cp => eastAsianWidth(cp) === 2),
    DEFAULT_IGNORABLE: ranges(prop('Default_Ignorable_Code_Point')),
    MARK: ranges(prop('Mark')),
    EXTENDED_PICTOGRAPHIC: ranges(prop('Extended_Pictographic')),
    EMOJI_PRESENTATION: ranges(prop('Emoji_Presentation')),
    EMOJI_MODIFIER: ranges(prop('Emoji_Modifier')),
    // emoji-regex matches the code point on its own
    EMOJI_SINGLE: ranges(cp => emojiRegex().test(String.fromCodePoint(cp))),
    // emoji-regex matches the code point followed by U+FE0F
    EMOJI_WITH_VS16: ranges(cp => emojiRegex().test(String.fromCodePoint(cp) + '️')),
    // emoji-regex matches the code point followed by an emoji modifier
    EMOJI_WITH_MODIFIER: ranges(cp => emojiRegex().test(String.fromCodePoint(cp) + '\u{1F3FB}'))
};

// Regional indicator pairs emoji-regex accepts as flags
const flags = [];
for (let a = 0x1f1e6; a <= 0x1f1ff; a++) {
    for (let b = 0x1f1e6; b <= 0x1f1ff; b++) {
        if (emojiRegex().test(String.fromCodePoint(a, b))) flags.push((a - 0x1f1e6) * 26 + (b - 0x1f1e6));
    }
}
const keycapNoVs = emojiRegex().test('1⃣');

let out = '// @generated by tools/gen-unicode-tables.mjs; do not edit.\n';
out += `// node ${process.version}, unicode ${process.versions.unicode}\n\n`;
for (const [name, rs] of Object.entries(tables)) {
    out += `pub static ${name}: &[(u32, u32)] = &[\n`;
    for (const [a, b] of rs) out += `    (0x${a.toString(16)}, 0x${b.toString(16)}),\n`;
    out += '];\n\n';
}
out += `pub static FLAG_PAIRS: &[u16] = &[${flags.join(', ')}];\n\n`;
out += `pub const KEYCAP_WITHOUT_VS16: bool = ${keycapNoVs};\n`;
process.stdout.write(out);
